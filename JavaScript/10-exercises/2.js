//Logical Operators

const hasTicket = true;
const isVip = false;
const isBanned = false;

console.log(hasTicket && isVip);
console.log(hasTicket || isVip);
console.log(!isVip);
console.log(hasTicket && !isBanned);
console.log(!hasTicket && isVip);
console.log(10 > 5 && 3 < 5);
console.log(10 > 5 || 3 < 5);
