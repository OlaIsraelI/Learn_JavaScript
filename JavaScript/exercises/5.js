//.Length, Zero-base Indexing and Case Method
const language = "JavaScript";

//The length of the variable language.
console.log(language.length);

//The first index of the variable language.
console.log(language[0]);

//The second index of the variable langauge.
console.log(language[1]);

//Select the index from the rear of the list.
console.log(language.at(-1));

//Format the strings in the variable language to upper case.
console.log(language.toUpperCase());

//Format the strings in the variable language to lower case.
console.log(language.toLowerCase());

//Print the actual string
console.log(language);
