//Using Maths object built in helper

let num1 = 2.5;
let num2 = 3.6;

console.log(num1 + num2);
console.log(Math.round(num1 + num2));
console.log(Math.floor(num1 + num2));
console.log(Math.ceil(num1 + num2));

//Maximum and Minimum number
console.log(Math.max(10, 25, 15, 30, 20, 35, 40));
console.log(Math.min(10, 25, 15, 30, 20, 35, 40));

//Absolute number
console.log(Math.abs(-25));

//Special value
console.log(0.1 + 0.2);
